"""Load the architecture CSV pack and render the Postgres schema.

The CSVs in docs/architecture are the source of truth for the database.
This module turns 02 (tables), 03 (columns) and 05 (RLS policies) into the
init migration, so the docs and the database cannot drift apart.
"""

from __future__ import annotations

import csv
import re
from dataclasses import dataclass, field
from pathlib import Path

RELEASE_ORDER = ["V1", "V1.5", "V2", "V3"]


@dataclass
class Column:
    table: str
    ordinal: int
    name: str
    type: str
    nullable: bool
    default: str
    primary_key: bool
    unique: bool
    foreign_key: str
    on_delete: str
    check: str
    indexed: bool
    description: str

    @property
    def is_identity(self) -> bool:
        return self.default.lower() == "generated always as identity"

    @property
    def sql_type(self) -> str:
        if self.type.startswith("vector("):
            return "extensions." + self.type
        return self.type


@dataclass
class Policy:
    table: str
    name: str
    command: str
    roles: str
    using: str
    with_check: str
    template: str


@dataclass
class Table:
    name: str
    domain: str
    purpose: str
    release: str
    retention: str
    primary_key: str
    unique_constraints: list[str]
    columns: list[Column] = field(default_factory=list)
    policies: list[Policy] = field(default_factory=list)

    @property
    def has_updated_at(self) -> bool:
        return any(c.name == "updated_at" for c in self.columns)


def _read(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def load(arch_dir: Path) -> list[Table]:
    tables: dict[str, Table] = {}
    for row in _read(arch_dir / "02_database_tables.csv"):
        uniques = re.findall(r"\(([^)]*)\)", row["unique_constraints"] or "")
        tables[row["table"]] = Table(
            name=row["table"],
            domain=row["domain"],
            purpose=row["purpose"],
            release=row["release"],
            retention=row["retention"],
            primary_key=row["primary_key"],
            unique_constraints=[u.strip() for u in uniques],
        )

    for row in _read(arch_dir / "03_database_columns.csv"):
        t = tables[row["table"]]
        t.columns.append(
            Column(
                table=row["table"],
                ordinal=int(row["ordinal"]),
                name=row["column"],
                type=row["type"],
                nullable=row["nullable"] == "yes",
                default=row["default"],
                primary_key=row["primary_key"] == "yes",
                unique=row["unique"] == "yes",
                foreign_key=row["foreign_key"],
                on_delete=row["on_delete"],
                check=row["check_constraint"],
                indexed=row["indexed"] == "yes",
                description=row["description"],
            )
        )

    for row in _read(arch_dir / "05_rls_policies.csv"):
        if row["policy"] == "(none)":
            continue
        tables[row["table"]].policies.append(
            Policy(
                table=row["table"],
                name=row["policy"],
                command=row["command"],
                roles=row["roles"],
                using=row["using"],
                with_check=row["with_check"],
                template=row["template"],
            )
        )

    for t in tables.values():
        t.columns.sort(key=lambda c: c.ordinal)
        pk_cols = [c.name for c in t.columns if c.primary_key]
        if pk_cols != [t.primary_key]:
            raise ValueError(f"{t.name}: primary key mismatch {pk_cols} vs {t.primary_key}")
    return list(tables.values())


def _q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def _fk_target(fk: str) -> tuple[str, str]:
    schema_table, col = fk.rsplit(".", 1)
    if "." in schema_table:
        return schema_table, col
    return "public." + schema_table, col


def render_sql(tables: list[Table], source_note: str) -> str:
    out: list[str] = []
    w = out.append
    w(f"-- GENERATED by tools/archgen from {source_note}. Do not edit by hand.")
    w("-- Regenerate with: python3 tools/archgen/build.py")
    w("")
    w("create extension if not exists pg_trgm with schema extensions;")
    w("create extension if not exists vector with schema extensions;")
    w("")
    w("create schema if not exists private;")
    w("revoke all on schema private from public;")
    w("grant usage on schema private to authenticated, service_role;")
    w("")
    w("create or replace function private.set_updated_at() returns trigger")
    w("language plpgsql set search_path = '' as $$")
    w("begin")
    w("  new.updated_at := now();")
    w("  return new;")
    w("end $$;")
    w("")

    # 1. Tables (no foreign keys yet, so creation order does not matter).
    for t in tables:
        w(f"-- {t.name} ({t.release}, {t.domain}): {t.purpose}")
        w(f"create table public.{t.name} (")
        defs: list[str] = []
        for c in t.columns:
            if c.is_identity:
                d = f"  {c.name} {c.sql_type} generated always as identity"
            else:
                d = f"  {c.name} {c.sql_type}"
                if c.default:
                    d += f" default {c.default}"
            if not c.nullable:
                d += " not null"
            defs.append(d)
        defs.append(f"  constraint {t.name}_pkey primary key ({t.primary_key})")
        for c in t.columns:
            if c.unique and not c.primary_key:
                defs.append(f"  constraint {t.name}_{c.name}_key unique ({c.name})")
        for i, u in enumerate(t.unique_constraints):
            cols = [x.strip() for x in u.split(",")]
            name = f"{t.name}_{'_'.join(cols)}_key"
            if len(name) > 63:
                name = f"{t.name}_uniq_{i + 1}"
            defs.append(f"  constraint {name} unique ({', '.join(cols)})")
        for c in t.columns:
            if c.check:
                defs.append(f"  constraint {t.name}_{c.name}_check check ({c.check})")
        w(",\n".join(defs))
        w(");")
        # Column descriptions live in 03_database_columns.csv and as JSDoc in database.ts.
        w(f"comment on table public.{t.name} is {_q(t.purpose + ' Retention: ' + t.retention + '.')};")
        w("")

    # 2. Foreign keys.
    w("-- Foreign keys")
    for t in tables:
        for c in t.columns:
            if not c.foreign_key:
                continue
            target, col = _fk_target(c.foreign_key)
            on_delete = f" on delete {c.on_delete}" if c.on_delete else ""
            w(
                f"alter table public.{t.name} add constraint {t.name}_{c.name}_fkey "
                f"foreign key ({c.name}) references {target} ({col}){on_delete};"
            )
    w("")

    # 3. Indexes (skip columns already covered by a PK/unique constraint).
    w("-- Indexes")
    for t in tables:
        covered = {t.primary_key} | {c.name for c in t.columns if c.unique}
        covered |= {u.split(",")[0].strip() for u in t.unique_constraints}
        for c in t.columns:
            if not c.indexed or c.name in covered:
                continue
            w(f"create index {t.name}_{c.name}_idx on public.{t.name} ({c.name});")
    w("")

    # 4. updated_at triggers.
    w("-- updated_at triggers")
    for t in tables:
        if t.has_updated_at:
            w(
                f"create trigger {t.name}_set_updated_at before update on public.{t.name} "
                f"for each row execute function private.set_updated_at();"
            )
    w("")

    # 5. RLS helpers (after tables because they read household_members).
    w("-- Row-level security helpers")
    w("create or replace function private.is_household_member(p_household uuid) returns boolean")
    w("language sql stable security definer set search_path = '' as $$")
    w("  select exists (")
    w("    select 1 from public.household_members m")
    w("    where m.household_id = p_household")
    w("      and m.user_id = (select auth.uid())")
    w("      and m.status = 'active'")
    w("  );")
    w("$$;")
    w("")
    w("create or replace function private.has_household_role(p_household uuid, p_roles text[]) returns boolean")
    w("language sql stable security definer set search_path = '' as $$")
    w("  select exists (")
    w("    select 1 from public.household_members m")
    w("    where m.household_id = p_household")
    w("      and m.user_id = (select auth.uid())")
    w("      and m.status = 'active'")
    w("      and m.role = any (p_roles)")
    w("  );")
    w("$$;")
    w("")
    w("revoke all on all functions in schema private from public;")
    w("grant execute on function private.is_household_member(uuid) to authenticated, service_role;")
    w("grant execute on function private.has_household_role(uuid, text[]) to authenticated, service_role;")
    w("")

    # 6. RLS policies.
    w("-- Row-level security policies")
    for t in tables:
        w(f"alter table public.{t.name} enable row level security;")
        if not t.policies:
            w(f"-- {t.name}: service_role only (no policies)")
        for p in t.policies:
            line = f"create policy {p.name} on public.{t.name} for {p.command} to {p.roles}"
            if p.using:
                line += f"\n  using ({p.using})"
            if p.with_check:
                line += f"\n  with check ({p.with_check})"
            w(line + ";")
        w("")

    # 7. Privileges: anon gets nothing; authenticated works only through RLS.
    w("-- Privileges")
    w("revoke all on all tables in schema public from anon;")
    w("grant select, insert, update, delete on all tables in schema public to authenticated;")
    w("grant all on all tables in schema public to service_role;")
    for t in tables:
        if t.policies == [] or all(p.template == "service_only" for p in t.policies):
            w(f"revoke all on public.{t.name} from authenticated;")
    w("")
    return "\n".join(out) + "\n"
