#!/usr/bin/env python3
"""Connect generated media to the app.

The images in apps/mobile/assets/media are made outside the repo (see PROMPTS.md there) and arrive over time.
Metro can only bundle files that exist, so this script writes src/design-system/media.ts with a require() for
every expected file that is present and `null` for the rest; screens fall back to a tinted shape on null.

    python3 tools/media/sync.py          # regenerate media.ts, report missing or wrongly sized files
    python3 tools/media/sync.py --check  # CI: fail if media.ts is out of date or a file has the wrong size
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "apps" / "mobile"
MEDIA = APP / "assets" / "media"
OUT = APP / "src" / "design-system" / "media.ts"

RECIPES = sorted(p.stem for p in (ROOT / "content" / "recipes").glob("*.yaml"))

# key -> (path under assets/media, width, height). Keep in step with PROMPTS.md.
ILLUSTRATIONS = {
    "emptyKitchen": ("illustrations/empty-kitchen.png", 480, 480),
    "emptyPicks": ("illustrations/empty-picks.png", 480, 480),
    "emptyList": ("illustrations/empty-list.png", 480, 480),
    "offline": ("illustrations/offline.png", 480, 480),
    "error": ("illustrations/error.png", 480, 480),
    "allDone": ("illustrations/all-done.png", 480, 480),
}
ONBOARDING = {
    "producePile": ("onboarding/produce-pile.png", 1179, 840),
    "leafPalak": ("onboarding/leaf-palak.png", 240, 240),
    "leafMethi": ("onboarding/leaf-methi.png", 240, 240),
    "leafCoriander": ("onboarding/leaf-coriander.png", 240, 240),
}
DISHES = {slug: (f"dishes/{slug}.png", 1080, 1080) for slug in RECIPES}


def png_size(path: Path) -> tuple[int, int] | None:
    with path.open("rb") as f:
        head = f.read(24)
    if head[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    return struct.unpack(">II", head[16:24])


def render() -> tuple[str, list[str]]:
    problems: list[str] = []

    def entry(key: str, rel: str, w: int, h: int, quote: bool) -> str:
        name = f'"{key}"' if quote else key
        path = MEDIA / rel
        if not path.exists():
            return f"  {name}: null,"
        size = png_size(path)
        if size is None:
            problems.append(f"{rel}: not a PNG")
        elif size != (w, h):
            problems.append(f"{rel}: is {size[0]}x{size[1]}, expected {w}x{h}")
        return f'  {name}: require("../../assets/media/{rel}") as ImageSourcePropType,'

    def block(name: str, items: dict, quote: bool = False) -> str:
        lines = [entry(k, *v, quote=quote) for k, v in items.items()]
        keys = " | ".join(f'"{k}"' for k in items)
        return f"export const {name}: Record<{keys}, ImageSourcePropType | null> = {{\n" + "\n".join(lines) + "\n};\n"

    src = (
        "// Generated by tools/media/sync.py from the files in assets/media. Do not edit; rerun the script.\n"
        "// null = not generated yet; the screen shows its tinted placeholder instead.\n"
        'import type { ImageSourcePropType } from "react-native";\n\n'
        + block("illustrations", ILLUSTRATIONS)
        + "\n"
        + block("onboarding", ONBOARDING)
        + "\n"
        + block("dishes", DISHES, quote=True)
        + "\n/** Photo for a recipe by slug, if one has been generated. */\n"
        "export function dishImage(slug: string): ImageSourcePropType | null {\n"
        "  return (dishes as Record<string, ImageSourcePropType | null>)[slug] ?? null;\n"
        "}\n"
    )
    return src, problems


def main() -> int:
    check = "--check" in sys.argv
    src, problems = render()
    all_items = {**ILLUSTRATIONS, **ONBOARDING, **DISHES}
    missing = [rel for rel, _, _ in all_items.values() if not (MEDIA / rel).exists()]
    for p in problems:
        print(f"wrong size: {p}", file=sys.stderr)
    if check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != src:
            print("media.ts is out of date: run python3 tools/media/sync.py", file=sys.stderr)
            return 1
        return 1 if problems else 0
    OUT.write_text(src)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(all_items) - len(missing)} of {len(all_items)} images present")
    for rel in missing:
        print(f"  still to generate: assets/media/{rel}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
